-- Adjoint, « Préparer le reçu » : correspondance produits WooCommerce → articles QuickBooks.
-- Contenu repris tel quel des tables du skill neo-leo-commandes (v5.0.0, catalogue
-- QuickBooks du 6 août 2026). Les prix ne sont jamais ici : ils viennent de la commande.
--   nom_woo        nom du produit sur la boutique (comparé sans ponctuation ni ™ ® *)
--   variante       format ou saveur ; mots_variante = mots qui doivent être dans la ligne
--   type           produit | livraison | retire (produit en voie de retrait : aucun article)
--   hors_boutique  jamais déduit d'une commande boutique (protéine de bœuf 1,6 kg)
-- Lecture et écriture : edge functions (clé service) seulement.

create table if not exists public.qbo_produits_map (
  id             bigint generated always as identity primary key,
  nom_woo        text not null,
  variante       text,
  mots_variante  text[] not null default '{}',
  article_qbo    text,
  item_ref       text,
  type           text not null default 'produit' check (type in ('produit', 'livraison', 'retire')),
  hors_boutique  boolean not null default false,
  actif          boolean not null default true,
  maj_le         timestamptz not null default now(),
  check (type = 'retire' or (article_qbo is not null and item_ref is not null))
);
create unique index if not exists qbo_produits_map_nom_variante on public.qbo_produits_map (nom_woo, coalesce(variante, ''));
alter table public.qbo_produits_map enable row level security;

